import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve, dirname } from "node:path";
import { createHash } from "node:crypto";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
import { run } from "../dist/servers/factory/process.js";
import assert from "node:assert/strict";
const npmCli=join(dirname(process.execPath),"node_modules/npm/bin/npm-cli.js");
await mkdir("release",{recursive:true});
const pack=await run({executable:process.execPath,args:[npmCli,"pack","--ignore-scripts","--pack-destination","release","--json"],timeoutSeconds:60},process.cwd());
assert.equal(pack.code,0,pack.output);
const metadata=JSON.parse(pack.stdout)[0],archive=resolve("release",metadata.filename);
assert.ok(metadata.files.some(f=>f.path==="dist/app/factory.html"));
assert.ok(metadata.files.some(f=>f.path==="scripts/codex-worker.mjs"));
for(const guide of ["setup.md","userguide.md"]) assert.ok(metadata.files.some(f=>f.path===guide),`Missing new-user guide: ${guide}`);
assert.ok(metadata.files.some(f=>f.path==="dist/servers/skills/ai-software-factory/references/roles.md"));
assert.ok(!metadata.files.some(f=>/\.db(?:-|$)|node_modules|^tests\/|^\.local-demo\//.test(f.path)));
const home=await mkdtemp(join(tmpdir(),"iron-clean-install-"));
let client;
try{
 const installed=await run({executable:process.execPath,args:[npmCli,"install","--prefix",home,archive,"--omit=dev","--prefer-offline","--no-audit","--no-fund"],timeoutSeconds:360},process.cwd());
 assert.equal(installed.code,0,installed.output);
 const entry=join(home,"node_modules/iron-legion-mcp/dist/servers/orchestrator/index.js");
 for(const guide of ["setup.md","userguide.md"]) assert.ok((await readFile(join(home,"node_modules/iron-legion-mcp",guide),"utf8")).startsWith("# "),`Installed guide is missing or empty: ${guide}`);
 const transport=new StdioClientTransport({command:process.execPath,args:[entry],env:{...process.env,IRON_LEGION_HOME:join(home,"state"),IRON_LEGION_CONFIG:join(home,"state/config.json")},stderr:"pipe"});
 client=new Client({name:"clean-package-acceptance",version:"1.0.0"});
 await client.connect(transport);
 assert.equal((await client.listTools()).tools.length,9);
 const resource=await client.readResource({uri:"ui://iron-legion/factory.html"});
 assert.equal(resource.contents[0].mimeType,"text/html;profile=mcp-app");
 const result=await client.callTool({name:"factory__open",arguments:{}});assert.ok(!result.isError);
 const legacy=await client.callTool({name:"tester__run_tests",arguments:{}});assert.ok(!legacy.isError);
 const sha256=createHash("sha256").update(await readFile(archive)).digest("hex");
 const evidence={status:"passed",archive:metadata.filename,bytes:metadata.size,files:metadata.entryCount,sha256,cleanInstall:true,compiledStdio:true,mcpAppResource:true,legacyTester:true,newUserGuides:true};
 await writeFile("release/package-verification.json",JSON.stringify(evidence,null,2)+"\n");
 await writeFile("release/SHA256SUMS.txt",`${sha256}  ${metadata.filename}\n`);
 console.log(JSON.stringify(evidence,null,2));
}finally{await client?.close();await rm(home,{recursive:true,force:true,maxRetries:4,retryDelay:300});}
